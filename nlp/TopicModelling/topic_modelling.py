from nltk.corpus import stopwords
from nltk.tokenize import word_tokenize
import string
import nltk

nltk.download('stopwords')
nltk.download('punkt')
nltk.download('punkt_tab')

documents = [
    "I love playing football with my friends on weekends.",
    "Artificial Intelligence and Machine Learning are transforming the tech world.",
    "Cricket is a popular sport in many countries.",
    "Deep learning is a subfield of machine learning.",
    "The football match yesterday was intense.",
]

def preprocess(doc):

  tokens = word_tokenize(doc)
  tokens = [w.lower() for w in tokens]
  tokems = [word for word in tokens if word.isalpha()]
  tokens = [word for word in tokens if word not in stopwords.words('english')]
  return tokens

preprocessed_doc = [preprocess(doc) for doc in documents]

from gensim import corpora

dictionary = corpora.Dictionary(preprocessed_doc)
corpus = [dictionary.doc2bow(doc) for doc in preprocessed_doc]

from gensim.models.ldamodel import LdaModel

lda_model = LdaModel(corpus=corpus, num_topics=2, id2word=dictionary)

topics = lda_model.print_topics(num_topics=2, num_words=4)
for topic in topics:
  print(topic)

